#!/usr/bin/env python3
"""Renders the Scoop manifest and Homebrew formula for a release.

Usage: packaging/render.py <version> <SHA256SUMS>
Writes bucket/argus.json and Formula/argus.rb at the repository root.
"""
import json
import pathlib
import sys

REPO = "https://github.com/serkankoyun/argus"
DESC = "Watch and steer your Claude Code agents live, from the terminal, on any machine."

version = sys.argv[1].lstrip("v")
sums = {}
for line in pathlib.Path(sys.argv[2]).read_text().splitlines():
    digest, name = line.split()
    sums[name.lstrip("*")] = digest

def asset(target, ext="tar.gz"):
    name = f"argus-v{version}-{target}.{ext}"
    return f"{REPO}/releases/download/v{version}/{name}", sums[name]

root = pathlib.Path(__file__).resolve().parent.parent

win_url, win_hash = asset("x86_64-pc-windows-msvc", "zip")
scoop = {
    "version": version,
    "description": DESC,
    "homepage": REPO,
    "license": "MIT",
    "architecture": {
        "64bit": {
            "url": win_url,
            "hash": win_hash,
            "extract_dir": f"argus-v{version}-x86_64-pc-windows-msvc",
        }
    },
    "bin": "argus.exe",
    "checkver": "github",
    "autoupdate": {
        "architecture": {
            "64bit": {
                "url": f"{REPO}/releases/download/v$version/argus-v$version-x86_64-pc-windows-msvc.zip",
                "extract_dir": "argus-v$version-x86_64-pc-windows-msvc",
            }
        },
        "hash": {"url": "$baseurl/SHA256SUMS"},
    },
}
(root / "bucket").mkdir(exist_ok=True)
(root / "bucket" / "argus.json").write_text(json.dumps(scoop, indent=2) + "\n")

mac_arm = asset("aarch64-apple-darwin")
mac_x86 = asset("x86_64-apple-darwin")
lin_arm = asset("aarch64-unknown-linux-gnu")
lin_x86 = asset("x86_64-unknown-linux-gnu")
formula = f'''# Generated by packaging/render.py for each release. Do not edit by hand.
class Argus < Formula
  desc "Watch and steer Claude Code agents live from the terminal"
  homepage "{REPO}"
  version "{version}"
  license "MIT"

  on_macos do
    on_arm do
      url "{mac_arm[0]}"
      sha256 "{mac_arm[1]}"
    end
    on_intel do
      url "{mac_x86[0]}"
      sha256 "{mac_x86[1]}"
    end
  end

  on_linux do
    on_arm do
      url "{lin_arm[0]}"
      sha256 "{lin_arm[1]}"
    end
    on_intel do
      url "{lin_x86[0]}"
      sha256 "{lin_x86[1]}"
    end
  end

  def install
    bin.install "argus"
    doc.install "README.md", "INSTALL.md"
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/argus --version")
  end
end
'''
(root / "Formula").mkdir(exist_ok=True)
(root / "Formula" / "argus.rb").write_text(formula)
print(f"rendered packages for {version}")
